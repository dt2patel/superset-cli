"""`tathya setup` - interactive first-run configuration.

Everything a cold install needs, in one pass: paste a base URL and credentials,
and the wizard discovers the rest from the instance itself. It exists because the
alternative - hand-editing TOML - requires knowing three things a newcomer cannot
know: that `base_url` must be an origin and not the page you were looking at,
that each database needs a `dialect` or valid MySQL is refused as unparseable,
and that nothing is queryable until it is allowlisted.

Each step is verified against the live instance before the next one, so a typo
surfaces where it was made rather than three commands later.
"""

from __future__ import annotations

import platform
import shutil
import sys

import httpx

from tathya import ops
from tathya.config import (
    BACKEND_TO_DIALECT,
    DEFAULT_CONFIG_TOML,
    config_path,
    normalize_base_url,
    watches_dir,
)
from tathya.context import Context
from tathya.errors import EXIT_OK, ConfigError, UsageError
from tathya.keychain import (
    GCHAT_WEBHOOK_ACCOUNT,
    account_for_password,
    get_secret,
    set_secret_interactive,
)

RULE = "─" * 66


def _say(text: str = "") -> None:
    print(text, file=sys.stderr)


def _step(number: int, total: int, title: str) -> None:
    _say()
    _say(f"[{number}/{total}] {title}")
    _say(RULE)


def _ask(prompt: str, default: str | None = None) -> str:
    suffix = f" [{default}]" if default else ""
    while True:
        answer = input(f"{prompt}{suffix}: ").strip()
        if answer:
            return answer
        if default is not None:
            return default
        _say("  A value is required.")


def _confirm(prompt: str, default: bool = True) -> bool:
    hint = "Y/n" if default else "y/N"
    answer = input(f"{prompt} [{hint}]: ").strip().lower()
    if not answer:
        return default
    return answer in {"y", "yes"}


# --------------------------------------------------------------------- probing
def _probe_instance(base_url: str, verify_tls: bool = True) -> dict:
    """Unauthenticated reachability check before asking for a password."""
    result: dict = {"reachable": False}
    try:
        with httpx.Client(base_url=base_url, timeout=15.0, verify=verify_tls,
                          follow_redirects=False) as client:
            health = client.get("/health")
            result["health_status"] = health.status_code
            result["health_body"] = health.text.strip()[:40]
            # The API answering 401 is the signal that this really is Superset.
            api = client.get("/api/v1/me/")
            result["api_status"] = api.status_code
            result["reachable"] = health.status_code < 500
            result["looks_like_superset"] = api.status_code in (401, 403, 200)
    except httpx.HTTPError as exc:
        result["error"] = str(exc)
    return result


def _probe_auth_provider(base_url: str, verify_tls: bool = True) -> str | None:
    """Guess db/ldap vs SSO from the login page. Advisory only."""
    try:
        with httpx.Client(base_url=base_url, timeout=15.0, verify=verify_tls,
                          follow_redirects=True) as client:
            page = client.get("/login/").text.lower()
    except httpx.HTTPError:
        return None
    has_password_field = 'type="password"' in page or "type='password'" in page
    mentions_sso = any(
        token in page for token in ("oauth", "sign in with", "single sign", "saml", "okta")
    )
    if has_password_field:
        return "form"
    if mentions_sso:
        return "sso"
    return None


def _fetch_databases(ctx_client) -> list[dict]:
    from tathya.rison import query as rison_query

    rows, _ = ctx_client.list_all(
        "/api/v1/database/",
        q_builder=lambda page, size: rison_query(
            columns=["id", "database_name", "backend", "expose_in_sqllab"],
            order_column="database_name", order_direction="asc",
            page=page, page_size=size,
        ),
        page_size=100,
    )
    return rows


def _render_toml(instance: dict, databases: list[dict]) -> str:
    lines = [
        "# tathya CLI configuration - generated by `tathya setup`.",
        "# Secrets are never stored here; they live in the macOS Keychain.",
        "",
        "[instance]",
        f'base_url = "{instance["base_url"]}"',
        f'username = "{instance["username"]}"',
        f'provider = "{instance["provider"]}"',
        "verify_tls = true",
        "timeout_seconds = 60",
        "",
        "[safety]",
        "# Conservative defaults. Loosen with evidence, not optimism.",
        f'max_rows = {instance["max_rows"]}',
        "hard_max_rows = 5000",
        "query_timeout_seconds = 45",
        "max_queries_per_minute = 6",
        "max_concurrent_queries = 1",
        "max_queries_per_day = 200",
        "require_estimate = false",
        "allow_delete = false",
        "blackout_windows = []",
        "",
        "[reporting]",
        'default_targets = ["local"]',
        'gchat_space_label = ""',
        "",
        "[digest]",
        'window = "6h"',
        "slow_query_seconds = 30",
        "failure_rate_pct = 10",
        "top_databases = 8",
        "",
        "# ---------------------------------------------------------------------------",
        "# Database allowlist - deny by default. Agents cannot query anything absent",
        "# from this list, even if the instance exposes it.",
        "# ---------------------------------------------------------------------------",
    ]
    if not databases:
        lines += ["", "# (none selected - `tathya sql run` will refuse every query)"]
    for entry in databases:
        lines += ["", "[[databases]]", f'name = "{entry["name"]}"', f'id = {entry["id"]}']
        if entry.get("dialect"):
            lines.append(f'dialect = "{entry["dialect"]}"   # from Superset backend '
                         f'{entry.get("backend")!r}')
        else:
            lines.append(f'# dialect unknown for backend {entry.get("backend")!r}; '
                         "set it if queries are refused as unparseable")
        lines.append(f'max_rows = {entry["max_rows"]}')
        if entry.get("note"):
            lines.append(f'note = "{entry["note"]}"')
    return "\n".join(lines) + "\n"


# ----------------------------------------------------------------------- wizard
def cmd_setup(ctx: Context) -> int:
    if not sys.stdin.isatty():
        raise UsageError(
            "`tathya setup` is interactive and needs a terminal.",
            hint="Run it yourself in a shell; the password prompt is deliberately not scriptable.",
        )

    total = 7
    path = config_path()
    _say()
    _say("tathya setup")
    _say(RULE)
    _say("Paste a base URL and credentials; the rest is discovered from the instance.")

    # ---- 1. preflight
    _step(1, total, "Environment")
    if platform.system() != "Darwin":
        raise ConfigError(
            f"Secret storage uses the macOS Keychain, but this is {platform.system()}.",
            hint="tathya is macOS-only today. Nothing was written.",
        )
    if not shutil.which("security"):
        raise ConfigError("The macOS `security` CLI was not found; Keychain storage is unavailable.")
    _say(f"  macOS, Python {platform.python_version()}, Keychain available")

    if path.exists() and not ctx.args.force:
        _say(f"  A config already exists at {path}")
        if not _confirm("  Overwrite it?", default=False):
            _say("  Nothing changed.")
            return EXIT_OK

    # ---- 2. base URL, verified before we ask for anything secret
    _step(2, total, "Superset instance")
    base_url = ""
    for attempt in range(4):
        raw = _ask("  Base URL (e.g. https://superset.example.com)")
        base_url, discarded = normalize_base_url(raw)
        if discarded:
            _say(f"  Using the origin {base_url} (dropped {discarded!r} - the CLI adds /api/v1 itself)")
        probe = _probe_instance(base_url)
        if probe.get("reachable") and probe.get("looks_like_superset"):
            _say(f"  Reachable: /health -> {probe['health_status']} {probe.get('health_body','')}, "
                 f"/api/v1/me/ -> {probe['api_status']} (expected, not logged in yet)")
            break
        if probe.get("error"):
            _say(f"  Could not reach it: {probe['error']}")
        else:
            _say(f"  Reached it, but it does not look like a Superset API "
                 f"(/health {probe.get('health_status')}, /api/v1 {probe.get('api_status')})")
        if attempt == 3:
            raise ConfigError("Could not verify the instance URL.", tried=base_url)
        _say("  Check VPN access and the URL, then try again.")

    # ---- 3. provider
    _step(3, total, "Authentication")
    guess = _probe_auth_provider(base_url)
    if guess == "sso":
        _say("  The login page looks SSO-only. Superset's API login has no OAuth branch,")
        _say("  so an SSO account cannot obtain a token - you need a db-provider service account.")
    elif guess == "form":
        _say("  The login page has a username/password form, so db or ldap will work.")
    provider = _ask("  Provider - 'db' for a Superset-local account, 'ldap' for directory", "db")
    while provider not in {"db", "ldap"}:
        _say("  Only 'db' and 'ldap' are supported by Superset's JWT login endpoint.")
        provider = _ask("  Provider", "db")
    username = _ask("  Username (exactly as typed on the login page)")

    # ---- 4. password -> Keychain
    _step(4, total, "Password")
    account = account_for_password(username)
    if get_secret(account) and not _confirm("  A password is already stored. Replace it?", default=False):
        _say("  Keeping the stored password.")
    else:
        _say("  Input is hidden and goes straight to the Keychain - never to a file or argv.")
        set_secret_interactive(account, f"Superset password for {username!r} at {base_url}")

    # Write a minimal config so the client can authenticate for discovery.
    path.parent.mkdir(parents=True, exist_ok=True)
    provisional = {"base_url": base_url, "username": username, "provider": provider, "max_rows": 500}
    path.write_text(_render_toml(provisional, []))
    path.chmod(0o600)

    from tathya.client import SupersetClient
    from tathya.config import load as load_config

    config = load_config(path)
    _step(5, total, "Verifying credentials")
    with SupersetClient(config) as client:
        try:
            client.auth.login()
        except Exception as exc:
            raise ConfigError(
                f"Login failed: {getattr(exc, 'message', exc)}",
                important="Do NOT retry in a loop - corporate LDAP commonly locks an account "
                          "after a few failures. The usual cause is username format "
                          "(e.g. 'you' vs 'you@example.com'), not a wrong password.",
                config_written=str(path),
            ) from exc
        _say("  Login succeeded, token issued.")

        # ---- 6. databases
        _step(6, total, "Database allowlist")
        _say("  Nothing is queryable until it is listed here. Keep it to the smallest useful set;")
        _say("  prefer an OLAP or read-replica database over a transactional one where both exist.")
        available = _fetch_databases(client)
        _say(f"  {len(available)} databases visible on this instance.")
        chosen: list[dict] = []
        if available:
            needle = input("  Filter by name (blank = show all): ").strip().lower()
            shown = [d for d in available
                     if not needle or needle in str(d.get("database_name", "")).lower()]
            shown = shown[:60]
            _say()
            for index, db in enumerate(shown, 1):
                backend = db.get("backend") or "?"
                dialect = BACKEND_TO_DIALECT.get(str(backend).lower())
                flag = "" if db.get("expose_in_sqllab") else "  (not in SQL Lab)"
                _say(f"   {index:>3}. {str(db.get('database_name'))[:40]:40} "
                     f"{backend:11} -> dialect {dialect or 'unknown'}{flag}")
            _say()
            picks = input("  Numbers to allowlist (e.g. 1,4,7 - blank for none): ").strip()
            for token in (p.strip() for p in picks.split(",")):
                if not token.isdigit():
                    continue
                position = int(token)
                if not 1 <= position <= len(shown):
                    _say(f"  Ignoring out-of-range choice {position}")
                    continue
                db = shown[position - 1]
                backend = str(db.get("backend") or "").lower()
                name = str(db.get("database_name"))
                cap = _ask(f"    Row cap for {name!r}", "500")
                chosen.append({
                    "name": name,
                    "id": int(db["id"]),
                    "backend": backend,
                    "dialect": BACKEND_TO_DIALECT.get(backend),
                    "max_rows": int(cap) if cap.isdigit() else 500,
                    "note": "",
                })

    instance = {"base_url": base_url, "username": username, "provider": provider, "max_rows": 500}
    path.write_text(_render_toml(instance, chosen))
    path.chmod(0o600)
    watches_dir().mkdir(parents=True, exist_ok=True)

    # ---- 7. optional extras
    _step(7, total, "Optional")
    installed_watches: list[str] = []
    if _confirm("  Install starter monitoring watches? (read Superset metadata only, no query cost)"):
        installed_watches = _install_starter_watches()
        _say(f"  Installed: {', '.join(installed_watches) or '(none)'}")
    if _confirm("  Store a Google Chat webhook for alerts now?", default=False):
        set_secret_interactive(GCHAT_WEBHOOK_ACCOUNT, "Google Chat webhook URL")

    summary = {
        "config": str(path),
        "base_url": base_url,
        "username": username,
        "provider": provider,
        "allowlisted_databases": [
            {"name": d["name"], "id": d["id"], "dialect": d["dialect"], "max_rows": d["max_rows"]}
            for d in chosen
        ],
        "watches_installed": installed_watches,
        "next_steps": [
            "tathya health           # confirm connectivity and the allowlist",
            "tathya digest           # production overview, costs no query budget",
            "tathya sql run <db> \"SELECT 1\"",
        ],
    }

    def human(data, line):
        line("")
        line("Setup complete.")
        line(RULE)
        line(f"  config      {data['config']}")
        line(f"  instance    {data['base_url']} as {data['username']} ({data['provider']})")
        if data["allowlisted_databases"]:
            for db in data["allowlisted_databases"]:
                line(f"  allowlisted {db['name']} (id {db['id']}, "
                     f"dialect {db['dialect'] or 'unset'}, max {db['max_rows']} rows)")
        else:
            line("  allowlisted (none) - `tathya sql run` will refuse until you add one")
        line("")
        line("Try:")
        for step in data["next_steps"]:
            line(f"  {step}")

    return ctx.emitter.ok("setup", summary, human=human)


def _install_starter_watches() -> list[str]:
    """Copy the ops-backed example watches, which cost no query budget."""
    import shutil as _shutil
    from pathlib import Path

    here = Path(__file__).resolve()
    candidates = [
        here.parents[1] / "_examples" / "watches",      # packaged in the wheel
        here.parents[3] / "examples" / "watches",       # source checkout
    ]
    source = next((c for c in candidates if c.exists()), None)
    target = watches_dir()
    target.mkdir(parents=True, exist_ok=True)
    installed: list[str] = []
    if source is None:
        return installed
    for candidate in sorted(source.glob("ops-*.yaml")):
        _shutil.copy2(candidate, target / candidate.name)
        installed.append(candidate.stem)
    return installed
